-- Migration: create price_anomalies table
-- Reason: new price anomaly enforcement feature. When a vendor tries
-- to save a price far above market average, the app warns them and,
-- if they proceed anyway, records it here so admin can review it.
-- Admin can also manually flag a price directly. Unresolved flags get
-- a daily reminder and, after 3 days, the vendor's whole stall is
-- deactivated (see create-price-anomaly-cron-job.sql) until admin
-- reactivates it.
--
-- Depends on: add-price-anomaly-notification-type.sql (run first —
-- the cron job and app code both write 'price_anomaly' notifications).
--
-- How to apply:
--   1. Open https://supabase.com/dashboard
